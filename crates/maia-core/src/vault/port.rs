//! `VaultStore` port types and trait.

use core::future::Future;

use crate::vault::error::VaultError;
use crate::vault::types::NoteFrontmatter;
use crate::vault::types::VaultPath;

/// Exact post-frontmatter note bytes returned by `VaultStore::read`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NoteBody(pub Vec<u8>);

/// One row in a folder index map result.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct VaultIndexEntry {
    /// Vault-relative wikilink target without `.md`.
    pub link: String,
    /// Child frontmatter description.
    pub description: String,
}

/// Navigation metadata returned by `VaultStore::map`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum VaultMap {
    /// Parsed folder `index.md` with child link rows.
    Index {
        /// Folder path, or `None` for the vault root index.
        path: Option<VaultPath>,
        /// Index frontmatter.
        frontmatter: NoteFrontmatter,
        /// Immediate child entries sorted by link.
        entries: Vec<VaultIndexEntry>,
    },
    /// Parsed frontmatter for a single non-index note.
    NoteHeader {
        /// Resolved note path.
        path: VaultPath,
        /// Note frontmatter.
        frontmatter: NoteFrontmatter,
    },
}

/// Staged generated bytes to apply atomically at the adapter boundary.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedVaultUpdate {
    /// Target note path relative to the vault root.
    pub path: VaultPath,
    /// Full new file contents.
    pub bytes: Vec<u8>,
    /// Content fingerprint observed when staging began (raw file bytes).
    pub expected_before: Vec<u8>,
}

/// Filesystem and watching capability for the Obsidian vault.
pub trait VaultStore {
    /// Returns index or header metadata; never returns non-index bodies.
    fn map(
        &self,
        path: Option<&VaultPath>,
    ) -> impl Future<Output = Result<VaultMap, VaultError>> + Send;

    /// Returns exact post-frontmatter bytes for a note file.
    fn read(&self, path: &VaultPath) -> impl Future<Output = Result<NoteBody, VaultError>> + Send;

    /// Atomically replaces generated files when the on-disk bytes still match staging.
    fn apply_generated(
        &self,
        update: &GeneratedVaultUpdate,
    ) -> impl Future<Output = Result<(), VaultError>> + Send;
}

/// Returns true when a path refers to a human-only personality note.
pub fn is_personality_note(path: &VaultPath) -> bool {
    let segments: Vec<&str> = path.as_str().split('/').collect();
    segments.len() == 3
        && segments[0] == "agents"
        && segments[2] == "personality"
        && !segments[1].is_empty()
}
